"""Copy every listing from samat-alsakan.com into the app.

    python3 scripts/sync_listings.py

Downloads the site's app.js, reads its listings (as JSON text; nothing from the site is executed), downloads each
listing image, shrinks it for phones (needs Pillow), and writes src/data/listings.generated.ts.
Run it again whenever listings change on the website, then rebuild the app.
"""
import io
import json
import os
import re
import urllib.request

from PIL import Image

SITE = "https://samat-alsakan.com"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_DIR = os.path.join(ROOT, "assets", "listings")
OUT = os.path.join(ROOT, "src", "data", "listings.generated.ts")
MAX_SIDE = 1400


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "listings-sync/1.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def read_listings(js: str) -> list:
    m = re.search(r"const FEATURED_PROPERTIES=(\[.*?\]\)?);\s*\n", js, re.S)
    if not m:
        raise SystemExit("Could not find the listings in app.js (the website's code changed).")
    src = m.group(1)
    src = re.sub(r"\]\s*\.concat\(\[", ",", src)
    src = re.sub(r"\]\)$", "]", src)
    src = re.sub(r",\s*([\]}])", r"\1", src)
    return json.loads(src)


def number(s) -> float | None:
    s = str(s or "").replace(",", "").strip()
    return float(s) if re.fullmatch(r"\d+(\.\d+)?", s) else None


def purpose(p: dict) -> str:
    if (p.get("transaction") or "") == "rent":
        return "rent"
    if "مطلوب" in p.get("titleAr", ""):
        return "wanted"
    return "sale"


def location(p: dict) -> str:
    title = p.get("titleAr", "")
    m = re.search(r"(?:في\s+)?(حي\s+[^–\-(،]+)", title)
    if m:
        return m.group(1).strip()
    m = re.search(r"(أبحر\s+(?:الشمالية|الجنوبية)|شرم أبحر|طريق المدينة|ريع بخش|الواجهة البحرية)", title)
    return m.group(1) if m else ""


def save_image(rel: str, name: str) -> str:
    im = Image.open(io.BytesIO(get(f"{SITE}/{rel}"))).convert("RGB")
    im.thumbnail((MAX_SIDE, MAX_SIDE))
    out = os.path.join(IMG_DIR, name + ".jpg")
    im.save(out, "JPEG", quality=80, optimize=True, progressive=True)
    return round(im.width / im.height, 4)


def main():
    os.makedirs(IMG_DIR, exist_ok=True)
    data = read_listings(get(f"{SITE}/app.js").decode("utf-8"))
    items = []
    for i, p in enumerate(data):
        slug = re.sub(r"[^a-z0-9-]", "-", p["id"].lower())
        ratio = save_image(p["image"], slug)
        price_n = number(p.get("price"))
        items.append({
            "id": p["id"],
            "source": "site",
            "order": i,
            "title": p.get("titleAr", "").strip(),
            "titleEn": p.get("titleEn", "").strip(),
            "type": (p.get("typeAr") or "").strip(),
            "city": (p.get("cityAr") or "").strip(),
            "location": location(p),
            "purpose": purpose(p),
            "price": price_n,
            "priceText": "" if price_n is not None else str(p.get("price") or "").strip(),
            "area": number(p.get("area")),
            "rooms": number(p.get("rooms")),
            "baths": number(p.get("bathrooms")),
            "description": (p.get("descriptionAr") or "").strip(),
            "details": [d.strip() for d in (p.get("detailsAr") or []) if str(d).strip()],
            "url": f"{SITE}/property.html?id={p['id']}",
            "imageRatio": ratio,
            "_img": slug,
        })
    lines = [
        "// GENERATED by scripts/sync_listings.py from samat-alsakan.com. Do not edit by hand; run the script again.",
        "import type { Listing } from './types';",
        "",
        "export const LISTINGS: Listing[] = [",
    ]
    for it in items:
        img = it.pop("_img")
        body = json.dumps(it, ensure_ascii=False)
        lines.append(f"  {{ ...{body}, image: require('../../assets/listings/{img}.jpg') }},")
    lines += ["];", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(items)} listings written to {os.path.relpath(OUT, ROOT)}; images in {os.path.relpath(IMG_DIR, ROOT)}")


if __name__ == "__main__":
    main()
